import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { recognizeProject } = require('../desktop-app/project-assets.js');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'jimeng-project-'));
fs.mkdirSync(path.join(root, '角色'), { recursive: true });
fs.mkdirSync(path.join(root, '背景'), { recursive: true });
fs.mkdirSync(path.join(root, 'BGM'), { recursive: true });
fs.mkdirSync(path.join(root, '视频素材'), { recursive: true });
fs.writeFileSync(path.join(root, '角色', '阮乔-常服.png'), 'x');
fs.writeFileSync(path.join(root, '背景', 'SC01.jpg'), 'x');
fs.writeFileSync(path.join(root, 'BGM', 'theme.mp3'), 'x');
fs.writeFileSync(path.join(root, '视频素材', 'out.mp4'), 'x');
fs.writeFileSync(path.join(root, '故事-分镜.txt'), 'x');
const started = performance.now();
const info = recognizeProject(root);
const elapsed = performance.now() - started;
assert.equal(info.folders.characters.relativePath, '角色');
assert.equal(info.folders.scenes.relativePath, '背景');
assert.equal(info.counts.characters, 1);
assert.equal(info.counts.scenes, 1);
assert.equal(info.counts.audio, 1);
assert.equal(info.documents.length, 1);
console.log(`[OK] project asset scan (${elapsed.toFixed(2)} ms)`);

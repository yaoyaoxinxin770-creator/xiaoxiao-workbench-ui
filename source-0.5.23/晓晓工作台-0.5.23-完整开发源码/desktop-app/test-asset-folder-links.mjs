import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const store=require('./asset-store'),library=require('./project-library'),{CdpBridge}=require('./cdp-bridge');
const analyzer=require('./project-assets').loadAnalyzer(path.resolve(import.meta.dirname,'../jimeng-canvas-extension/analyzer.js'));
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'folder-link-test-'));
const project=path.join(temp,'空项目'),scene=path.join(temp,'原场景'),male=path.join(temp,'男主'),female=path.join(temp,'女主'),audio=path.join(temp,'音色');
try {
  for(const dir of [project,scene,male,female,audio])fs.mkdirSync(dir);
  fs.writeFileSync(path.join(scene,'大厅.png'),'scene-original');
  fs.writeFileSync(path.join(scene,'excluded.mp4'),'video');
  fs.mkdirSync(path.join(scene,'未高清'));fs.writeFileSync(path.join(scene,'未高清','大厅-旧.png'),'nested-excluded');
  fs.mkdirSync(path.join(audio,'旧音频'));fs.writeFileSync(path.join(audio,'旧音频','阮乔-旧.wav'),'nested-audio-excluded');
  fs.writeFileSync(path.join(male,'阮乔.png'),'male-original');
  fs.writeFileSync(path.join(female,'小红.png'),'female-original');
  fs.writeFileSync(path.join(audio,'阮乔.wav'),'audio-original');
  fs.mkdirSync(path.join(project,'成品'));fs.writeFileSync(path.join(project,'成品','预览.png'),'excluded');
  fs.writeFileSync(path.join(project,'旧参考.png'),'old');
  store.write(project,{workspace:'jimeng'});
  store.linkFolder(project,'scenes',scene);store.linkFolder(project,'characters',male);store.linkFolder(project,'characters',female);store.linkFolder(project,'audio',audio);
  store.linkFolder(project,'characters',male);
  assert.equal(store.read(project).folderLinks.length,4,'重复绑定不建重复索引');
  assert.throws(()=>store.linkFolder(project,'video',scene),/只能绑定/);
  assert.throws(()=>store.linkFolder(project,'props',scene),/其他分类/);
  const source='视频编号01｜场景：大厅｜人物：阮乔、小红';
  const collected=store.collect(project,analyzer,source);
  assert.equal(collected.assets.length,4,'只索引选定图片与音频，不混入成品及视频');
  assert.equal(collected.assets.filter(item=>item.kind==='characters').length,2);
  const linkedScene=collected.assets.find(item=>item.kind==='scenes');
  assert.equal(store.inside(project,linkedScene.relativePath),path.join(scene,'大厅.png'));
  assert.equal(fs.readFileSync(store.inside(project,linkedScene.relativePath),'utf8'),'scene-original');
  assert.throws(()=>store.inside(project,linkedScene.relativePath.replace('大厅.png','../男主/阮乔.png')));
  assert.throws(()=>store.inside(project,'@linked/not-registered/大厅.png'));
  assert.throws(()=>store.inside(project,'../原场景/大厅.png'));
  fs.symlinkSync(male,path.join(scene,'outside'),'junction');
  assert.throws(()=>store.inside(project,linkedScene.relativePath.replace('大厅.png','outside/阮乔.png')),/链接/);
  assert.equal(store.collect(project,analyzer,source).assets.length,4,'跳过越界链接');
  const staging={sources:new Map()};
  const staged=CdpBridge.prototype.stage.call(staging,[{root:project,relativePath:linkedScene.relativePath}]);
  assert.equal(staging.sources.get(staged[0].transferId).file,path.join(scene,'大厅.png'),'发送读原文件，非复制品');
  assert.equal(staged[0].size,Buffer.byteLength('scene-original'));
  assert.throws(()=>store.inside(project,linkedScene.relativePath.replace('大厅.png','未高清/大厅-旧.png')),/最外层/,'子文件不能沿用旧引用上传');
  const list=library.list(project,analyzer);
  assert.equal(list.items.length,4);
  assert.ok(list.items.every(item=>item.source==='element'&&item.mediaType!=='video'));
  assert.ok(list.folders.some(item=>item.title==='原场景'));
  assert.equal(list.folderLinks.length,4);
  const second=store.collect(project,analyzer,source);
  assert.deepEqual(second.assets.map(item=>item.relativePath),collected.assets.map(item=>item.relativePath),'重新读取保持路径索引');
  assert.deepEqual(fs.readdirSync(project).sort(),['.jimeng','成品','旧参考.png'].sort(),'未复制任何原素材');
  store.unlinkFolder(project,collected.assets.find(item=>item.kind==='scenes').folderLinkId);
  assert.equal(store.collect(project,analyzer,source).assets.length,3);
  assert.ok(fs.existsSync(path.join(scene,'大厅.png')),'解除绑定保留原文件');
  assert.throws(()=>store.inside(project,linkedScene.relativePath),/未绑定/);
  fs.renameSync(audio,audio+'-moved');
  const missing=store.collect(project,analyzer,source);
  assert.equal(missing.assets.length,2);assert.match(missing.warnings.join('\n'),/请重新绑定/);
  const char=store.collect(project,analyzer,source).assets.find(item=>item.kind==='characters');
  const config=store.read(project);config.segmentCharacterBindings={'video:01:0':{小红:char.relativePath}};config.segmentAssetBindings={'video:01:0':{characters:[char.relativePath],scenes:[],other:[]}};store.write(project,config);
  assert.throws(()=>store.clearReferences(project,['unknown.png'],analyzer),/索引已变化/);
  const cleared=store.clearReferences(project,[char.relativePath],analyzer);assert.equal(cleared.cleared,1);
  assert.equal(store.collect(project,analyzer,source).assets.length,1,'所选清空保留其他素材');
  assert.equal(store.read(project).segmentCharacterBindings['video:01:0'].小红,undefined);
  assert.deepEqual(store.read(project).segmentAssetBindings['video:01:0'].characters,[]);
  assert.ok(fs.existsSync(char.sourcePath));assert.throws(()=>store.inside(project,char.relativePath),/引用已清空/);
  assert.throws(()=>CdpBridge.prototype.stage.call(staging,[{root:project,relativePath:char.relativePath}]),/引用已清空/);
  assert.equal(library.list(project,analyzer).items.length,1,'重载索引不恢复已清空项');
  const kept=store.collect(project,analyzer,source).assets[0];store.clearReferences(project,null,analyzer);
  assert.equal(store.collect(project,analyzer,source).assets.length,0);assert.deepEqual(store.read(project).folderLinks,[]);
  assert.ok(fs.existsSync(kept.sourcePath));assert.ok(fs.existsSync(path.join(scene,'未高清','大厅-旧.png')));
  assert.equal(library.list(project,analyzer).items.length,0,'全部清空重启不恢复');
  store.linkFolder(project,'characters',male);assert.equal(store.collect(project,analyzer,source).assets.length,1,'重新绑定可重新索引原文件');
  store.clearReferences(project,null,analyzer);
  fs.writeFileSync(path.join(male,'额外.png'),'not-selected');
  store.linkFiles(project,'characters',[path.join(male,'阮乔.png'),path.join(female,'小红.png')]);
  let selectedFiles=store.collect(project,analyzer,source);
  assert.equal(selectedFiles.assets.length,2,'选文件只索引选择的文件，不带入同目录其他图');
  const selectedMale=selectedFiles.assets.find(item=>item.sourcePath===path.join(male,'阮乔.png'));
  assert.equal(store.inside(project,selectedMale.relativePath),path.join(male,'阮乔.png'));
  assert.throws(()=>store.inside(project,selectedMale.relativePath.replace('阮乔.png','额外.png')),/未被选中/);
  assert.throws(()=>store.linkFiles(project,'audio',[path.join(male,'阮乔.png')]),/图片|音频|类型/);
  store.linkFiles(project,'audio',[path.join(audio+'-moved','阮乔.wav')]);
  assert.equal(store.collect(project,analyzer,source).assets.length,3);
  store.clearReferences(project,[selectedMale.relativePath],analyzer);
  store.linkFiles(project,'characters',[path.join(male,'阮乔.png')]);
  assert.equal(store.collect(project,analyzer,source).assets.length,3,'重新选择已清空文件可恢复引用');
  fs.writeFileSync(path.join(male,'同目录对白.wav'),'mixed-original');
  store.linkFiles(project,'audio',[path.join(male,'同目录对白.wav')]);
  assert.equal(store.collect(project,analyzer,source).assets.length,4,'同目录可分别引用图片和音频');
  assert.throws(()=>store.linkFiles(project,'scenes',[path.join(male,'阮乔.png')]),/其他分类/,'同一图片不能重复分类');
  store.linkFolder(project,'characters',male);
  assert.equal(store.collect(project,analyzer,source).assets.length,5,'绑定整个文件夹升级为外层全文件索引');
  assert.deepEqual(fs.readdirSync(project).sort(),['.jimeng','成品','旧参考.png'].sort(),'选图片和音频不复制到项目目录');
  // 拖入的绝对路径按目录名/扩展名自动归入对应分类，仍只建引用不复制。
  const drop=path.join(temp,'拖放来源'),dropProject=path.join(temp,'拖放项目');
  fs.mkdirSync(path.join(drop,'场景'),{recursive:true});fs.mkdirSync(path.join(drop,'人物'),{recursive:true});fs.mkdirSync(dropProject);
  fs.writeFileSync(path.join(drop,'场景','大厅.png'),'drop-scene');fs.writeFileSync(path.join(drop,'人物','小红.png'),'drop-character');
  fs.writeFileSync(path.join(drop,'x.mp3'),'drop-audio');fs.writeFileSync(path.join(drop,'readme.txt'),'note');
  store.write(dropProject,{workspace:'jimeng'});
  const linkResult=await require('./asset-ipc').createActions({}).linkPaths(dropProject,'all',[path.join(drop,'场景','大厅.png'),path.join(drop,'人物','小红.png'),path.join(drop,'x.mp3'),path.join(drop,'readme.txt')]);
  assert.equal(linkResult.linked,3);assert.equal(linkResult.skipped,1);
  assert.deepEqual(linkResult.config.folderLinks.map(link=>link.kind).sort(),['audio','characters','scenes']);
  const dropAssets=store.collect(dropProject,analyzer,source).assets;
  assert.equal(dropAssets.length,3);assert.equal(store.inside(dropProject,dropAssets.find(item=>item.kind==='scenes').relativePath),path.join(drop,'场景','大厅.png'));
  assert.deepEqual(fs.readdirSync(dropProject),['.jimeng'],'拖放引用也不复制原文件');
  console.log('分类目录原路径索引：多目录、无复制、排除视频、持久化、预览/发送原文件、越界防护、解除及失效提示通过');
} finally {
  assert.ok(path.resolve(temp).startsWith(path.resolve(os.tmpdir())+path.sep)&&path.basename(temp).startsWith('folder-link-test-'));
  fs.rmSync(temp,{recursive:true,force:true,maxRetries:10,retryDelay:100});
}

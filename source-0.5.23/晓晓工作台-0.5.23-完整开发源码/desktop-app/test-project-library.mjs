import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import http from 'node:http';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const library=require('./project-library');
const store=require('./asset-store');
const core=require('./typetale-core');
const {createBrowserWorkbenchHandler}=require('./browser-workbench-service');
const testRoot=fs.mkdtempSync(path.join(os.tmpdir(),'xiaoxiao-library-test-'));
const project=path.join(testRoot,'项目'), external=path.join(testRoot,'外部文件'), destination=path.join(testRoot,'导出');
const analyzer={matchCharacterPrefix:(name,roles)=>roles.find(role=>name.startsWith(role)) || '',isLikelyGroupCharacter:()=>false};
const write=(relative,value)=>{const file=path.join(project,relative);fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,value);};
let server;
try {
  fs.mkdirSync(external,{recursive:true});fs.mkdirSync(destination);
  write('人物/小红.png','image');write('音频/小红.mp3','voice');
  for(let n=0;n<7;n++)write(`typetale-output/0001_01_${n}_0.mp4`,'0123456789');
  const history=Array.from({length:7},(_,n)=>({path:`typetale-output/0001_01_${n}_0.mp4`,createdAt:`2026-10-0${n+1}T00:00:00Z`,prompt:`历史提示词${n}`,model:'test-model',providerName:'test-provider'}));
  const state=core.normalizeState({projectPath:project,chapters:[{id:'c1',name:'第一章'}],shots:[{id:'01',chapterId:'c1',viewerIndex:1,prompt:'后来修改的提示词',results:history}],assets:[]});
  assert.equal(state.shots[0].results.length,7,'归一化不能截断历史');
  write('.typetale/workbench.json',JSON.stringify(state));
  let result=library.list(project,analyzer);
  assert.equal(result.items.filter(item=>item.source==='result').length,7);
  assert.equal(result.items.filter(item=>item.source==='element').length,2,'输入素材不伪装成生成结果');
  const output=result.items.find(item=>item.relativePath.endsWith('_6_0.mp4'));
  assert.ok(output.groupIds.includes('shot:01')&&output.groupIds.includes('chapter:c1'),'镜头结果计入父章节');
  assert.equal(output.prompt,'历史提示词6','预览保留生成时的提示词');
  assert.equal(output.model,'test-model');
  const id='file:人物/小红.png';
  library.edit(project,[id,output.id],{status:'approved'});
  library.edit(project,[id],{elementStatus:'draft'});
  library.saveBrief(project,'项目简介正文');
  result=library.list(project,analyzer);
  assert.equal(result.brief,'项目简介正文');
  assert.equal(result.items.find(item=>item.id===id).status,'approved');
  assert.equal(result.items.find(item=>item.id===id).elementStatus,'draft');
  store.edit(project,'人物/小红.png',{displayName:'小红正面',role:'小红',category:'characters',audio:'音频/小红.mp3'});
  result=library.list(project,analyzer);
  assert.equal(result.items.find(item=>item.id===id).displayName,'小红正面','Elements 与原素材绑定共享同一份配置');
  assert.equal(store.read(project).audioBindings.小红,'音频/小红.mp3');
  assert.throws(()=>library.edit(project,[id],{status:'fake'}));
  assert.throws(()=>library.preview(project,'../外部文件/秘密.mp4'));
  const incoming=path.join(external,'成片.mp4');fs.writeFileSync(incoming,'result');
  const first=library.importResults(project,[incoming],'shot:01');
  const second=library.importResults(project,[incoming],'chapter:c1');
  assert.notEqual(first.added[0],second.added[0],'同名导入不覆盖原文件');
  assert.equal(fs.readFileSync(incoming,'utf8'),'result','导入复制原文件');
  result=library.list(project,analyzer);
  assert.ok(result.items.find(item=>item.relativePath===first.added[0]).groupIds.includes('chapter:c1'));
  library.exportFiles(project,[first.added[0],first.added[0]],destination);
  library.exportFiles(project,[first.added[0]],destination);
  assert.equal(fs.readdirSync(destination).length,2,'重复导出不覆盖且同次去重');
  assert.throws(()=>library.exportFiles(project,['../外部文件/成片.mp4'],destination));
  const url=library.preview(project,output.relativePath).preview;
  const handler=createBrowserWorkbenchHandler({root:testRoot,actions:{}});
  server=http.createServer(async(req,res)=>{if(!await handler(req,res)){res.writeHead(404);res.end();}});
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const address=`http://127.0.0.1:${server.address().port}${new URL(url).pathname}`;
  const partial=await fetch(address,{headers:{Range:'bytes=2-5'}});
  assert.equal(partial.status,206);assert.equal(partial.headers.get('content-range'),'bytes 2-5/10');assert.equal(await partial.text(),'2345');
  assert.equal((await fetch(address,{headers:{Range:'bytes=99-100'}})).status,416);
  assert.equal((await fetch(address,{headers:{Origin:'https://evil.example'}})).status,403);
  assert.equal((await fetch(address.replace(/[a-f0-9]{48}$/,'0'.repeat(48)))).status,404,'不能通过猜路径读取文件');
  assert.equal((await fetch(address,{method:'HEAD'})).headers.get('content-length'),'10');
  console.log('Project library: full history, shared Elements, grouping, review persistence, safe import/export and media ranges passed');
} finally {
  if(server)await new Promise(resolve=>server.close(resolve));
  const resolved=path.resolve(testRoot);
  assert.ok(resolved.startsWith(path.resolve(os.tmpdir())+path.sep)&&path.basename(resolved).startsWith('xiaoxiao-library-test-'));
  fs.rmSync(resolved,{recursive:true,force:true});
}
